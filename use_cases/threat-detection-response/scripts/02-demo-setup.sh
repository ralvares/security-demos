#!/usr/bin/env bash
# 02-demo-setup.sh — build, deploy and arm the demo.
#
#   1. build blog v1/v2 + attacker kit with podman, push to the CRC internal registry
#   2. let RHACS scan the internal registry (image integration)
#   3. deploy blog + payments-api   (the attacker lives on this laptop: scripts/attacker.sh)
#   4. load the TDR runtime policies (policy as code) + enable "Unauthorized Network Flow"
#   5. generate normal traffic, then LOCK process + network baselines
#
#   scripts/02-demo-setup.sh            full setup (idempotent)
#   SKIP_BUILD=1 scripts/02-demo-setup.sh   reuse already-pushed images
#   scripts/02-demo-setup.sh --apps     only steps 1+3 (no RHACS needed: run while RHACS installs)
set -euo pipefail
source "$(dirname "$0")/lib/common.sh"
source "$TDR_DIR/scripts/lib/rhacs-baselines.sh"
need oc podman jq curl roxctl
use_crc
APPS_ONLY=""; [[ ${1:-} == --apps ]] && APPS_ONLY=1

REG_ROUTE=$(oc get route default-route -n openshift-image-registry -o jsonpath='{.spec.host}')

# ---------------------------------------------------------------- namespaces
step "Namespaces"
oc apply -f "$TDR_DIR/deploy/app/namespace.yaml" >/dev/null
oc delete namespace attacker --ignore-not-found --wait=false >/dev/null 2>&1   # older versions ran the attacker in-cluster
ok "$APP_NS, $PAY_NS"

# ---------------------------------------------------------------- images
if [[ -z ${SKIP_BUILD:-} ]]; then
  step "Build + push images → $REG_ROUTE"
  podman login -u kubeadmin -p "$(oc whoami -t)" --tls-verify=false "$REG_ROUTE" >/dev/null
  for v in v1 v2; do
    podman build -q --build-arg VARIANT=$v -t "$REG_ROUTE/$APP_NS/blog:$v" "$TDR_DIR/app/blog" >/dev/null
    podman push -q --tls-verify=false "$REG_ROUTE/$APP_NS/blog:$v"
    ok "blog:$v"
  done
  podman build -q -t localhost/attacker-kit:latest "$TDR_DIR/app/attacker-kit" >/dev/null
  ok "attacker-kit (local only — runs on this laptop)"
fi
# payments-api runs the blog image from the unhackable namespace
oc policy add-role-to-group system:image-puller "system:serviceaccounts:$PAY_NS" -n "$APP_NS" >/dev/null 2>&1
ok "payments may pull from $APP_NS"

deploy_workloads() {
  step "Deploy the Unhackable Blog and payments-api"
  # recreate: every setup starts with fresh RHACS process + network baselines
  oc delete -f "$TDR_DIR/deploy/app/blog.yaml" --ignore-not-found --wait=true >/dev/null 2>&1 || true
  oc apply -f "$TDR_DIR/deploy/app/blog.yaml" >/dev/null
  oc delete networkpolicy -A -l tdr-demo=response --ignore-not-found >/dev/null
  for d in "$APP_NS/blog"; do
    oc rollout status "deploy/${d#*/}" -n "${d%/*}" --timeout=300s >/dev/null && ok "$d"
  done
  BLOG=https://$(oc get route blog -n "$APP_NS" -o jsonpath='{.spec.host}')
  ok "blog: $BLOG"
}
if [[ -n $APPS_ONLY ]]; then
  deploy_workloads
  printf '\n%sApps deployed.%s RHACS parts (policies, baselines) run with: make setup / make up\n' "$GRN" "$N"
  exit 0
fi

load_rhacs
central_up() { curl -sfk "https://$ROX_ENDPOINT/v1/ping" && rox GET /v1/auth/status | jq -e .userId; }
wait_for "Central API" 600 central_up

# ---------------------------------------------------------------- registry integration
step "RHACS ↔ internal registry"
oc apply -f - >/dev/null <<EOF
apiVersion: v1
kind: ServiceAccount
metadata: { name: stackrox-image-puller, namespace: stackrox }
---
apiVersion: v1
kind: Secret
metadata:
  name: stackrox-image-puller-token
  namespace: stackrox
  annotations: { kubernetes.io/service-account.name: stackrox-image-puller }
type: kubernetes.io/service-account-token
EOF
oc policy add-role-to-user system:image-puller system:serviceaccount:stackrox:stackrox-image-puller -n "$APP_NS" >/dev/null 2>&1
wait_for "puller token" 60 oc get secret stackrox-image-puller-token -n stackrox -o jsonpath='{.data.token}'
REG_TOKEN=$(oc get secret stackrox-image-puller-token -n stackrox -o jsonpath='{.data.token}' | base64 -d)
INTEG_NAME="CRC internal registry (tdr-demo)"
existing=$(rox GET /v1/imageintegrations | jq -r --arg n "$INTEG_NAME" '.integrations[]? | select(.name==$n) | .id')
body=$(jq -n --arg n "$INTEG_NAME" --arg e "$REGISTRY_SVC" --arg p "$REG_TOKEN" --arg id "$existing" '
  {name:$n, type:"docker", categories:["REGISTRY"], autogenerated:false, skipTestIntegration:true,
   docker:{endpoint:$e, username:"stackrox-image-puller", password:$p, insecure:true}} + (if $id != "" then {id:$id} else {} end)')
if [[ -n $existing ]]; then rox PUT "/v1/imageintegrations/$existing?updatePassword=true" "$body" >/dev/null
else rox POST /v1/imageintegrations "$body" >/dev/null; fi
ok "$INTEG_NAME → $REGISTRY_SVC"

# ---------------------------------------------------------------- workloads
deploy_workloads

# ---------------------------------------------------------------- policies
step "Runtime policies (policy as code)"
oc apply -f "$TDR_DIR/rhacs/policies/" >/dev/null
for p in "$TDR_DIR"/rhacs/policies/*.yaml; do
  n=$(basename "$p" .yaml)
  accepted() { oc get securitypolicy "$1" -n stackrox -o json | jq -e '[.status.conditions[]? | select(.type=="AcceptedByCentral" and .status=="True")] | length > 0'; }
  if wait_for "$n accepted by Central" 120 accepted "$n"; then :; fi
done
# The built-in network-baseline policy stays at its default (disabled): on a single-node
# cluster every DNS lookup shows up as a new UDP flow. tdr-lateral-movement applies the
# same criterion to payments-api, which never does DNS — so it only fires on real anomalies.
nf_id=$(rox GET "/v1/policies?query=$(uri 'Policy:Unauthorized Network Flow')" | jq -r '.policies[0].id // empty')
[[ -n $nf_id ]] && rox PATCH "/v1/policies/$nf_id" '{"disabled":true}' >/dev/null && ok "built-in 'Unauthorized Network Flow' left disabled (see tdr-lateral-movement)"

# ---------------------------------------------------------------- baselines
step "Teach RHACS what normal looks like"
info "browsing + legitimate link checks (the blog serves natively — no child processes spawn)"
for i in $(seq 1 6); do
  curl -sk -o /dev/null "$BLOG/" ; curl -sk -o /dev/null "$BLOG/post/zero-cves"; curl -sk -o /dev/null "$BLOG/write"
  curl -sk -o /dev/null -XPOST "$BLOG/api/links/check" -d '{"urls":["https://www.redhat.com/en","https://access.redhat.com"]}'
  sleep 5
done
ok "normal traffic generated"
info "letting the flows reach Central before locking (90s)"; sleep 90

blog_seen() { [[ -n $(rox_deployment_id "$APP_NS" blog) ]]; }
wait_for "RHACS sees the blog" 300 blog_seen
pb_ready() {
  local id; id=$(rox_deployment_id "$APP_NS" blog)
  rox GET "/v1/processes/deployment/$id" | jq -e '[.processes[]?.signal.execFilePath] | index("/usr/local/bin/blog") != null'
}
wait_for "process events for blog" 300 pb_ready

# Declare the blog's baseline EXACTLY (whatever else setup may have triggered is dropped), then lock.
blog_id=$(rox_deployment_id "$APP_NS" blog)
# The blog spawns no child processes (native net/http + in-process rule engine), so the whole
# legitimate baseline is a single binary. Declare it exactly.
legit=(/usr/local/bin/blog)
rhacs-pb-replace "$APP_NS/blog" blog "${legit[@]}" >/dev/null && ok "process baseline set: ${legit[*]}"
rhacs-pb-lock "$APP_NS/blog"            >/dev/null && ok "process baseline LOCKED: $APP_NS/blog"
# Network baseline: the blog is exposed through the route, so its one legitimate peer is the
# router's ingress on 8080. Declare it, drop anything else the traffic above triggered (the
# unbounded internet egress of a link checker can't be baselined), then lock — so the network
# graph shows router → blog as expected and only the attack's flows stand out. Same as the
# per-run path (fresh_blog in demo.sh).
rhacs-nb-add "$APP_NS/blog" --peer openshift-ingress/router-default --port 8080 --ingress >/dev/null
rhacs-nb-forbid-external "$APP_NS/blog" >/dev/null 2>&1 || true
rhacs-nb-lock "$APP_NS/blog"            >/dev/null && ok "network baseline = router ingress :8080, LOCKED: $APP_NS/blog"
fresh_payments
rhacs-pb-list "$APP_NS/blog" 2>/dev/null | sed 's/^/    /' || true

# ---------------------------------------------------------------- Scanner V4 ready?
scan_ok() { roxctl -e "$ROX_ENDPOINT" image scan --image "$REGISTRY_SVC/$APP_NS/blog:v1" --force --output json >/dev/null 2>&1; }
wait_for "Scanner V4 vulnerability database loaded (first install: up to 30 min)" 2400 scan_ok
roxctl -e "$ROX_ENDPOINT" image scan --image "$REGISTRY_SVC/$APP_NS/blog:v2" --force --output json >/dev/null 2>&1 || true

# ---------------------------------------------------------------- clean slate
"$TDR_DIR/scripts/demo.sh" resolve >/dev/null 2>&1 || true

# ---------------------------------------------------------------- attacker
"$TDR_DIR/scripts/attacker.sh" up

cat <<EOF

${GRN}${B}Demo armed.${N}
  blog:     $BLOG
  status:   scripts/demo.sh status
  run:      see README.md — start with: scripts/demo.sh act1
EOF
